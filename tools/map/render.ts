// Cairn's map pages: the rows from evidence.ts → static HTML (docs/map.md, "Pages").
//
// Pure: returns { path: html }. One page per place, one for invariants and assumptions, the
// Evidence page, and the index with the summary. Every claim gets an element whose id is its
// number, so `page.html#12` cites `^12`.
import { counts, gaps, KINDS, type Claim, type EvidenceKind, type Headline, type Mark, type Row, type Step } from "./evidence";

export type Context = {
	app: string;
	rows: Row[];
	/** Size of each image the pages use, in CSS pixels. */
	size: (file: string) => [number, number] | undefined;
	/** A line on what the build had: fuzz, conformance, capture, audit. */
	inputs: string[];
	retiredElsewhere: { id: number; title: string }[];
	code: string;
};

type Page = { file: string; title: string; claims: Row[]; place?: Row };

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
/** Prose from the build: escaped, with `code` spans. */
const md = (s: string) => esc(s).replace(/`([^`]+)`/g, "<code>$1</code>");
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const witnessOf = (c: Claim): Step[] => (Array.isArray(c.witness) ? c.witness : []);

const ABOUT: Record<EvidenceKind, string> = {
	proved: "Lean checked every theorem it names, with the standard axioms only.",
	fuzzed: "Random sequences of moves, checked after every step, found no failure.",
	tested: "The running app, driven through generated sequences, matched the model.",
	seen: "A headless capture of the app's own frames shows it.",
	assumed: "Stated and relied on, never proved.",
};
const HEADLINES: Headline[] = ["broken", ...KINDS, "untested", "retired"];

export function render(ctx: Context): Record<string, string> {
	const { rows, app } = ctx;
	const byId = new Map(rows.map((r) => [r.claim.id, r]));

	// Pages: one per place (its moves, and the flows that start there), then the guarantees.
	const placeOf = (c: Claim) => (c.kind === "flow" ? (c.place ?? byId.get(witnessOf(c)[0]?.claim ?? -1)?.claim.place ?? null) : c.place);
	const places = rows.filter((r) => r.claim.kind === "place");
	const used = new Set<string>(["index", "evidence", "guarantees", "elsewhere"]);
	const pages: Page[] = places.map((p) => {
		let file = slug(p.claim.title) || `place-${p.claim.id}`;
		if (used.has(file)) file = `${file}-${p.claim.id}`;
		used.add(file);
		return { file: `${file}.html`, title: p.claim.title, place: p, claims: [p, ...rows.filter((r) => (r.claim.kind === "move" || r.claim.kind === "flow") && placeOf(r.claim) === p.claim.id)] };
	});
	const placed = new Set(pages.flatMap((p) => p.claims.map((r) => r.claim.id)));
	const elsewhere = rows.filter((r) => (r.claim.kind === "move" || r.claim.kind === "flow") && !placed.has(r.claim.id));
	if (elsewhere.length) pages.push({ file: "elsewhere.html", title: "Not in a place", claims: elsewhere });
	const guarantees = rows.filter((r) => r.claim.kind === "invariant" || r.claim.kind === "assume");
	if (guarantees.length) pages.push({ file: "guarantees.html", title: "Invariants and assumptions", claims: guarantees });
	const pageOf = new Map<number, string>();
	for (const p of pages) for (const r of p.claims) pageOf.set(r.claim.id, p.file);
	const href = (id: number, from?: string) => `${pageOf.get(id) === from ? "" : (pageOf.get(id) ?? "evidence.html")}#${id}`;
	const ref = (s: { ref: string; claim: number }, from?: string) => `<a class="id" href="${href(s.claim, from)}">${esc(s.ref)}</a>`;

	const nav = (on: string) =>
		`<nav class="bar"><a class="home" href="../../"><img src="icon.svg" alt="">Cairn</a><span class="sep">/</span>` +
		[["index.html", `${esc(app)} map`], ...pages.map((p) => [p.file, esc(p.title)]), ["evidence.html", "Evidence"]].map(([f, t]) => `<a href="${f}"${f === on ? ' class="on"' : ""}>${t}</a>`).join("") +
		`</nav>`;
	const shell = (file: string, title: string, body: string) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="Every claim ${esc(app)} makes, with the evidence the build has for it.">
<link rel="icon" href="icon.svg" type="image/svg+xml">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Pixelify+Sans:wght@400..700&display=swap" rel="stylesheet">
<link rel="stylesheet" href="style.css">
</head>
<body>
${nav(file)}
<main>
${body}
</main>
<footer>Generated by <code>make map APP=${esc(app)}</code> from the claims and the build. Nothing here is written by hand.</footer>
<script type="module">
// On the site, the headings get the meadow's sprigs (site/public/scene.js); elsewhere, nothing.
import("/scene.js").then((m) => m.mountSprigs(document.querySelector("main"))).catch(() => {});
</script>
</body>
</html>
`;

	const chip = (m: Mark) => `<span class="m ${m.kind} ${m.state}" title="${esc(m.detail.replace(/`/g, ""))}">${esc(m.label)}</span>`;
	const marks = (r: Row) => `<span class="marks">${r.marks.map(chip).join("")}</span>`;
	const headline = (h: Headline) => `<span class="hl ${h}">${h}</span>`;
	const img = (file: string, alt: string, caption = "") => {
		const [w, h] = ctx.size(file) ?? [];
		return `<figure class="shot"><div class="box px"><img src="img/${esc(file)}" alt="${esc(alt)}"${w ? ` width="${w}" height="${h}"` : ""} loading="lazy"></div>${caption ? `<figcaption>${caption}</figcaption>` : ""}</figure>`;
	};

	// ---- A claim ---------------------------------------------------------------------------------
	const claim = (r: Row, from: string) => {
		const c = r.claim;
		const said = [c.does && `<b>Does</b><p>${md(c.does)}</p>`, c.sees && `<b>Sees</b><p>${md(c.sees)}</p>`].filter(Boolean).join("");
		const ev = r.marks.length ? `<dl class="ev">${r.marks.map((m) => `<dt>${chip(m)}</dt><dd>${md(m.detail)}</dd>`).join("")}</dl>` : "";
		const findings = r.findings.map((f) => `<p class="finding${f.broken ? "" : " soft"}">${md(f.text)}</p>`).join("");
		const thms = r.theorems.length
			? `<details><summary>${r.theorems.length} theorem${r.theorems.length === 1 ? "" : "s"}</summary><div class="thm">${r.theorems.map((t) => `<div><span class="${t.ok ? "ok" : "bad"}">${t.ok ? "✓" : "✗"}</span> <code>${esc(t.theorem.replace(/^Examples\./, ""))}</code> <span class="muted">${esc(t.role)}</span></div>`).join("")}</div></details>`
			: "";
		const src = `<p class="src"><a href="${ctx.code}${esc(c.pos.file)}${c.pos.line ? `#L${c.pos.line}` : ""}">${esc(c.pos.file)}${c.pos.line ? `:${c.pos.line}` : ""}</a> · <code>${esc(c.decl.replace(/^Examples\./, ""))}</code> · ledger: ${esc(r.ledger)}</p>`;
		let pictures = "";
		let witness = "";
		if (c.kind === "move" && r.shots.after)
			pictures = `<div class="pair">${img(r.shots.before!, `${c.title}, before`, "before")}${img(r.shots.after, `${c.title}, after`, "after")}</div>`;
		else if (c.kind === "move" && r.shots.frames[0]) pictures = img(r.shots.frames[0], c.title, "in a captured frame; not performed");
		if (c.kind === "flow") {
			const steps = witnessOf(c);
			witness = steps.length ? `<b class="pix muted">Witness</b><ol class="witness">${steps.map((s) => `<li>${esc(s.trigger)} ${ref({ ref: s.ref, claim: s.claim }, from)}${s.op ? ` <code>${esc(op(s.op))}</code>` : ""}</li>`).join("")}</ol>` : "";
			if (r.shots.frames.length)
				pictures = `<div class="strip">${r.shots.frames
					.map((f, k) => (k ? `<span class="arrow">→</span>` : "") + img(f, `${c.title}, ${k ? `after step ${k}` : "start"}`, k ? `${k}. ${esc(steps[k - 1]!.trigger)} ${esc(steps[k - 1]!.ref)}` : "start"))
					.join("")}</div>${r.shots.complete ? "" : `<p class="finding soft">The replay stopped early.</p>`}`;
		}
		const wide = c.kind !== "move" || !pictures || !!r.shots.after;
		return `<section class="claim px" id="${c.id}">
<div class="head"><a class="id" href="#${c.id}">${esc(c.ref)}</a><h3>${esc(c.title)}</h3><span class="pix muted">${c.kind}</span>${headline(r.headline)}</div>
<div class="body${wide ? " wide" : ""}"><div class="said">${c.retired ? `<p class="retired-why">Retired: ${md(c.retired)}</p>` : said}${witness}${ev}${findings}${thms}${src}</div>${wide ? "" : `<div>${pictures}</div>`}</div>
${wide ? pictures : ""}
</section>`;
	};

	const out: Record<string, string> = {};

	// ---- Place pages and the guarantees ------------------------------------------------------------
	for (const p of pages) {
		const moves = p.claims.filter((r) => r.claim.kind === "move");
		const flows = p.claims.filter((r) => r.claim.kind === "flow");
		const inv = p.claims.filter((r) => r.claim.kind === "invariant");
		const asm = p.claims.filter((r) => r.claim.kind === "assume");
		const section = (title: string, rs: Row[]) => (rs.length ? `<h2>${title} <span class="n">${rs.length}</span></h2>\n${rs.map((r) => claim(r, p.file)).join("\n")}` : "");
		const head = p.place
			? `<header class="page"><div class="eyebrow">${esc(app)} · place ${esc(p.place.claim.ref)}</div><h1 id="${p.place.claim.id}">${esc(p.title)}</h1><p class="lede">${md(p.place.claim.does)}</p>${marks(p.place)}</header>
${p.place.shots.frames[0] ? `<div class="hero">${img(p.place.shots.frames[0], `${p.title}, as the app starts`, "As the app starts. Pins come from the frame's layout: each control is labelled with its claim.")}</div>` : ""}`
			: `<header class="page"><div class="eyebrow">${esc(app)}</div><h1>${esc(p.title)}</h1><p class="lede">${p.file === "guarantees.html" ? "What holds in every state the app can reach (proved), and what the proofs take as given about the world (assumed)." : "Moves and flows that name no place."}</p></header>`;
		out[p.file] = shell(p.file, `${p.title} · ${app} map`, `${head}\n${section("Moves", moves)}\n${section("Flows", flows)}\n${section("Invariants", inv)}\n${section("Assumptions", asm)}`);
	}

	// ---- The index: the summary, the gaps, every claim ------------------------------------------
	const n = counts(rows);
	const g = gaps(rows).sort((a, b) => Number(b.broken) - Number(a.broken));
	const tile = (k: (typeof n.kinds)[number]) =>
		`<div class="tile ${k.kind}"><div class="k">${k.kind}</div><div class="v">${k.of ? `${k.have}<small> / ${k.of}</small>` : `<small>none</small>`}${k.fail ? ` <span class="bad">${k.fail} failed</span>` : ""}</div><div class="d">${ABOUT[k.kind]}</div></div>`;
	const spread = HEADLINES.filter((h) => n.headlines.get(h)).map((h) => `<i class="${h}" style="--n:${n.headlines.get(h)};--c:var(--${h})" title="${n.headlines.get(h)} ${h}"></i>`).join("");
	const legend = HEADLINES.filter((h) => n.headlines.get(h)).map((h) => `<span>${headline(h)} <b>${n.headlines.get(h)}</b></span>`).join("");
	// Gaps that share a cause (no fuzz file, say) are one row naming every claim they touch.
	const grouped = [...Map.groupBy(g, (x) => `${x.what}\u0000${x.detail}`).values()];
	const gapRows = grouped.length
		? `<div class="wrap"><table class="gaps"><thead><tr><th>Missing or failed</th><th>Claims</th><th>Why</th></tr></thead><tbody>${grouped
				.map((xs) => `<tr class="${xs[0]!.broken ? "broken" : ""}"><td class="what"><span class="m gap">${esc(xs[0]!.what)}</span></td><td>${xs.map((x) => `<a class="id" href="${href(x.row.claim.id)}" title="${esc(x.row.claim.title)}">${esc(x.row.claim.ref)}</a>${xs.length === 1 ? ` ${esc(x.row.claim.title)}` : ""}`).join(", ")}</td><td>${md(xs[0]!.detail)}</td></tr>`)
				.join("")}</tbody></table></div>`
		: `<p class="none">None: every claim has every kind of evidence it can have.</p>`;
	const slots = (r: Row) => KINDS.map((k) => `<td class="slot">${r.marks.find((m) => m.kind === k) ? chip(r.marks.find((m) => m.kind === k)!) : ""}</td>`).join("");
	const claimRow = (r: Row) =>
		`<tr${r.claim.retired ? ' class="retired"' : ""}><td class="id"><a class="id" href="${href(r.claim.id)}">${esc(r.claim.ref)}</a></td><td>${esc(r.claim.title)}</td><td class="kind">${r.claim.kind}</td><td>${headline(r.headline)}</td>${slots(r)}</tr>`;
	const claimTable = `<div class="wrap"><table class="claims"><thead><tr><th>Id</th><th>Claim</th><th>Kind</th><th>Reads as</th>${KINDS.map((k) => `<th>${k}</th>`).join("")}</tr></thead><tbody>${pages
		.map((p) => `<tr class="group"><td colspan="${4 + KINDS.length}"><a href="${p.file}">${esc(p.title)}</a></td></tr>${p.claims.map(claimRow).join("")}`)
		.join("")}</tbody></table></div>`;
	out["index.html"] = shell(
		"index.html",
		`${app} map`,
		`<header class="page"><div class="eyebrow">Cairn · map</div><h1>${esc(app)}</h1>
<p class="lede">Every claim ${esc(app)} makes, and the evidence the build has for each: what Lean proved, what the fuzzer and the conformance driver ran, and what a capture of the app shows.</p></header>
<section class="summary"><div class="card px">
<div class="tiles">${n.kinds.map(tile).join("")}</div>
<div class="spread" aria-hidden="true">${spread}</div>
<div class="legend">${legend}</div>
<p class="inputs">${n.live} live claim${n.live === 1 ? "" : "s"}${n.total > n.live ? ` (and ${n.total - n.live} retired)` : ""}. Each reads as the strongest evidence it holds, unless something failed (<a href="evidence.html#ladder">the ladder</a>). ${ctx.inputs.map(md).join(" · ")}</p>
</div></section>
<h2>Gaps <span class="n">${g.length}</span></h2>
<p class="prose muted">Evidence a claim could have and doesn't, failures first.</p>
${gapRows}
<h2>Claims <span class="n">${rows.length}</span></h2>
${claimTable}`,
	);

	// ---- The Evidence page ------------------------------------------------------------------------
	const evRow = (r: Row) =>
		`<tr${r.claim.retired ? ' class="retired"' : ""}><td class="id"><a class="id" href="${href(r.claim.id)}">${esc(r.claim.ref)}</a></td><td class="kind">${r.claim.kind}</td><td>${esc(r.claim.title)}</td><td>${headline(r.headline)}</td>${slots(r)}<td class="thm">${r.theorems.map((t) => `<div><span class="${t.ok ? "ok" : "bad"}">${t.ok ? "✓" : "✗"}</span> <code>${esc(t.theorem.replace(/^Examples\./, ""))}</code></div>`).join("")}</td><td class="muted">${esc(r.ledger)}</td></tr>`;
	out["evidence.html"] = shell(
		"evidence.html",
		`Evidence · ${app} map`,
		`<header class="page"><div class="eyebrow">${esc(app)} · evidence</div><h1>Evidence</h1>
<p class="lede">One row per claim, every column computed from the build. Hover a chip for what it rests on.</p></header>
<div class="wrap"><table class="claims"><thead><tr><th>Id</th><th>Kind</th><th>Claim</th><th>Reads as</th>${KINDS.map((k) => `<th>${k}</th>`).join("")}<th>Theorems (axiom audit)</th><th>Ledger</th></tr></thead>
<tbody>${rows.map(evRow).join("\n")}</tbody></table></div>
${ctx.retiredElsewhere.length ? `<h2>Retired elsewhere</h2><p class="prose">Retired ids in <code>claims.lock</code> that no module declares any more: ${ctx.retiredElsewhere.map((l) => `<code>^${l.id}</code> ${esc(l.title)}`).join(", ")}.</p>` : ""}
<h2 id="ladder">The ladder</h2>
<div class="prose">
<p>A claim shows every kind of evidence it has. It <em>reads as</em> the strongest of them, so a proved invariant reads as proved whatever else ran. Strongest first:</p>
<ol class="ladder">
<li><span class="m proved pass">proved</span><span>Every theorem the claim names (each move handler's <code>sound</code>; a flow's <code>live</code> and <code>reaches</code>; an invariant's <code>init</code>, <code>step</code> and <code>reachable</code>) is in <code>lake exe audit --json</code> and uses only <code>propext</code>, <code>Classical.choice</code> and <code>Quot.sound</code>. <code>make check</code> also replays every declaration through the kernel.</span></li>
<li><span class="m fuzzed pass">fuzzed N</span><span>N random sequences of the Lean model and runtime (<code>make fuzz</code>, docs/fuzz.md), with each invariant's check, presence and pressability after every step. For an assumption, the trusted-base fuzzer (<code>build/fuzz/trusted.json</code>) found no counterexample.</span></li>
<li><span class="m tested pass">tested N</span><span>The running app, driven through its debug socket by generated sequences (<code>make conformance</code>, docs/conformance.md), matched the model's frame, accessibility tree, effects and pixels after every step. N counts the steps that exercised a move.</span></li>
<li><span class="m seen pass">seen</span><span>A headless capture of the app's own frames, drawn by the real renderer, shows the control (for a move), the whole witness performed on the controls it names (for a flow), or the window (for a place).</span></li>
<li><span class="m assumed pass">assumed</span><span>An <code>assume</code>: stated, never proved. Theorems that rely on it take it as a hypothesis.</span></li>
</ol>
<p>Two more readings: <span class="hl broken">broken</span> when any evidence failed (a theorem missing or using another axiom, a fuzz or conformance failure, or a capture that contradicts a live witness), and <span class="hl untested">untested</span> when a live claim has no evidence at all. A dashed chip, <span class="m gap">not tested</span>, is evidence the claim could have and doesn't: a gap.</p>
<p>Proved and fuzzed are about the Lean model; tested and seen are about the app. A proof is the stronger statement, but only conformance reaches through the host, so a claim is fully covered when it has every chip its kind allows: a move can be proved, fuzzed, tested and seen; a flow proved, tested and seen; an invariant proved, fuzzed and tested; a place seen.</p>
</div>`,
	);

	// Every claim must be citable: its id is an element on some page.
	for (const r of rows) {
		const page = out[pageOf.get(r.claim.id) ?? ""];
		if (!page || !page.includes(` id="${r.claim.id}"`)) throw new Error(`^${r.claim.id} is on no page`);
	}
	return out;
}

function op(o: unknown) {
	if (o && typeof o === "object" && "kind" in o) {
		const { kind, ...rest } = o as Record<string, unknown>;
		return `${kind}${Object.values(rest).length ? ` ${Object.values(rest).map((v) => JSON.stringify(v)).join(" ")}` : ""}`;
	}
	return JSON.stringify(o);
}
